"""Rule and Ruin vertical slice: module mount fits measured on the actual hulls (Blender 5.x).

Run:  blender -b --factory-startup --python Tools/Blender/rr_mounts.py
Ray-casts each flagship FBX at the stations where the capital-ship modules sit and writes
Assets/RR/Game/ShipMounts.g.cs: how wide to set the lateral modules (afterburner pods, ablative plating) so they sit on the
hull's flanks, and how far to lift the dorsal battery so it sits on the spine. Module meshes are authored for a hull of
length 1 centred on its bounds (rr_ships.py MODULES); everything here is in those normalised units. rr_design_sheet.py
uses the same measurement, so the reference renders and the game agree.
"""
import bpy, os
from mathutils import Vector

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
MODELS = os.path.join(ROOT, "Assets", "RR", "Art", "Models")
OUT_CS = os.path.join(ROOT, "Assets", "RR", "Game", "ShipMounts.g.cs")

FLAGSHIPS = ["pygmaei_revenant_command_ship", "inhumanus_executive_flagship"]
# Authored module stations, normalised (y forward, z up, relative to the hull's bounds centre).
STERN_Y, AFTERBURNER_X = -0.3, 0.18
AMIDSHIPS_Y, PLATING_X = -0.11, 0.2
DORSAL_Y, BATTERY_BASE_Z = -0.06, 0.17


def bounds(meshes):
    pts = [m.matrix_world @ Vector(c) for m in meshes for c in m.bound_box]
    lo = Vector((min(p.x for p in pts), min(p.y for p in pts), min(p.z for p in pts)))
    hi = Vector((max(p.x for p in pts), max(p.y for p in pts), max(p.z for p in pts)))
    return lo, hi


def cast(origin, direction):
    dg = bpy.context.evaluated_depsgraph_get()
    hit, loc, *_ = bpy.context.scene.ray_cast(dg, origin, direction)
    return loc if hit else None


def half_width(c, length, y, z_band):
    """The hull's half-width at station y: the widest of rays cast inward from both sides across a band of heights."""
    best = 0.0
    for dz in z_band:
        for side in (1, -1):
            o = c + Vector((side * length * 3, y * length, dz * length))
            hit = cast(o, Vector((-side, 0, 0)))
            if hit is not None:
                best = max(best, abs(hit.x - c.x) / length)
    return best


def measure(meshes):
    """Normalised fit numbers for one hull (already imported, meshes in the scene)."""
    bpy.context.view_layer.update()
    lo, hi = bounds(meshes)
    c = (lo + hi) / 2
    length = max(hi.x - lo.x, hi.y - lo.y)
    band = [k * 0.02 for k in range(-3, 4)]
    hw_stern = half_width(c, length, STERN_Y, band) or (hi.x - lo.x) / 2 / length
    hw_mid = half_width(c, length, AMIDSHIPS_Y, band) or (hi.x - lo.x) / 2 / length
    top = None
    for dx in (0.0, 0.03, -0.03):
        hit = cast(c + Vector((dx * length, DORSAL_Y * length, length * 3)), Vector((0, 0, -1)))
        if hit is not None:
            t = (hit.z - c.z) / length
            top = t if top is None else max(top, t)
    if top is None:
        top = (hi.z - c.z) / length
    return {
        "afterburner_width": (hw_stern + 0.01) / AFTERBURNER_X,    # pod centres just outboard of the flank
        "plating_width": (hw_mid + 0.012) / PLATING_X,              # plates against the flank
        "battery_lift": top - 0.01 - BATTERY_BASE_Z,                # turret base just inside the spine
        "length": length,
    }


def import_hull(name):
    before = set(bpy.data.objects)
    bpy.ops.import_scene.fbx(filepath=os.path.join(MODELS, name + ".fbx"))
    return [o for o in bpy.data.objects if o not in before and o.type == 'MESH']


def main():
    rows = []
    for name in FLAGSHIPS:
        bpy.ops.wm.read_factory_settings(use_empty=True)
        f = measure(import_hull(name))
        rows.append((name, f))
        print("mount", name, {k: round(v, 4) for k, v in f.items()})
    lines = [
        "// <auto-generated> by Tools/Blender/rr_mounts.py from the hull FBX files. Do not edit; rerun the script after changing a hull or a module.",
        "using System.Collections.Generic;",
        "",
        "namespace RR.Game",
        "{",
        "    public static partial class ShipModules",
        "    {",
        "        /// <summary>Per-hull module fits, measured by ray casts on the hull: lateral width factors and the dorsal lift (hull lengths).</summary>",
        "        static readonly Dictionary<string, (float afterburnerWidth, float platingWidth, float batteryLift)> Mounts =",
        "            new Dictionary<string, (float, float, float)>",
        "        {",
    ]
    for name, f in rows:
        lines.append(f'            ["{name}"] = ({f["afterburner_width"]:.4f}f, {f["plating_width"]:.4f}f, {f["battery_lift"]:.4f}f),')
    lines += ["        };", "    }", "}", ""]
    with open(OUT_CS, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("wrote", OUT_CS)


if __name__ == "__main__":
    main()
