"""Validate Assets/RR/Content/slice_content.json and generate Assets/RR/Vendor/Core/Roster/SliceContent.g.cs.

Usage (from the repository root):  python Tools/Content/rr_content.py [--check]

--check validates and reports without writing. The schema is deliberately small: module sidegrades (stat deltas the rules
already apply through SliceRules.ApplyModules) and scenario loadouts made of existing roster hulls. Anything that needs new
behaviour (a new ability, targeting rule or effect) is not content: it needs a rules handler, its preview, AI legality and a
regression test first, and this script refuses unknown fields so such data cannot slip in unnoticed.
The runtime validator (RR.Strategy.SliceContentCheck) repeats the checks against the live roster.
"""
import json, re, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'Assets', 'RR', 'Content', 'slice_content.json')
OUT = os.path.join(ROOT, 'Assets', 'RR', 'Vendor', 'Core', 'Roster', 'SliceContent.g.cs')
CATALOG = os.path.join(ROOT, 'Assets', 'RR', 'Vendor', 'Core', 'Roster', 'RosterCatalog.g.cs')

SLOTS = {'propulsion', 'protection', 'firepower'}
STATS = ['move', 'armor', 'hull', 'damage', 'range']
VISUALS = {'afterburners', 'ablative_plating', 'heavy_battery'}   # module meshes in the art library
MODULE_FIELDS = set(['id', 'name', 'slot', 'visual', 'cost', 'summary'] + STATS)
LOADOUT_FIELDS = {'id', 'faction', 'domain', 'name', 'units', 'note'}
FACTIONS = {'Pygmaei', 'Inhumanus'}


def roster_ids():
    text = open(CATALOG, encoding='utf-8').read()
    return set(re.findall(r'Unit\("([a-z_]+)", "([a-z]+)"', text))


def validate(data):
    errors = []
    if data.get('schema') != 'rr.slice.content' or data.get('version') != 1:
        errors.append('schema must be "rr.slice.content", version 1')
    ids = set()
    for i, m in enumerate(data.get('modules', [])):
        where = f"module {m.get('id', i)}"
        extra = set(m) - MODULE_FIELDS
        if extra: errors.append(f'{where}: unknown field(s) {sorted(extra)} (new behaviour needs a rules handler, not content)')
        if not re.fullmatch(r'[a-z][a-z0-9_]{2,31}', m.get('id', '')): errors.append(f'{where}: id must be lower_snake_case, 3-32 characters')
        if m.get('id') in ids: errors.append(f'{where}: duplicate id')
        ids.add(m.get('id'))
        if m.get('slot') not in SLOTS: errors.append(f'{where}: slot must be one of {sorted(SLOTS)}')
        if m.get('visual') not in VISUALS: errors.append(f'{where}: visual must name an existing module mesh {sorted(VISUALS)}')
        deltas = [m.get(s, 0) for s in STATS]
        if any(not isinstance(d, int) or abs(d) > 3 for d in deltas): errors.append(f'{where}: stat changes must be whole numbers between -3 and 3')
        if not any(d > 0 for d in deltas) or not any(d < 0 for d in deltas): errors.append(f'{where}: a sidegrade needs at least one gain and one cost')
        cost = m.get('cost', {})
        if set(cost) != {'energy', 'materials', 'credits'} or any(not isinstance(v, int) or v < 0 for v in cost.values()) or sum(cost.values()) == 0:
            errors.append(f'{where}: cost needs energy, materials and credits (whole, not negative, not all zero)')
        if not m.get('name') or not m.get('summary', '').endswith('.'): errors.append(f'{where}: name and a summary sentence are required')
    known = roster_ids()
    lids = set()
    for i, l in enumerate(data.get('loadouts', [])):
        where = f"loadout {l.get('id', i)}"
        extra = set(l) - LOADOUT_FIELDS
        if extra: errors.append(f'{where}: unknown field(s) {sorted(extra)}')
        if l.get('id') in lids: errors.append(f'{where}: duplicate id')
        lids.add(l.get('id'))
        if l.get('faction') not in FACTIONS: errors.append(f'{where}: faction must be one of {sorted(FACTIONS)}')
        if l.get('domain') != 'Orbital': errors.append(f'{where}: only orbital loadouts are supported')
        fk = (l.get('faction') or '').lower()
        for u in l.get('units', []):
            if (u, fk) not in known: errors.append(f'{where}: {u} is not a {l.get("faction")} unit in the roster')
        if not l.get('units') or len(l['units']) > 8: errors.append(f'{where}: 1 to 8 units')
    return errors


def cs(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def generate(data):
    lines = ['// <auto-generated>',
             '// Generated by Tools/Content/rr_content.py from Assets/RR/Content/slice_content.json. Do not edit by hand:',
             '// change the JSON and re-run the script. The rules apply these through SliceRules.ApplyModules (no new code per module).',
             '// </auto-generated>', '',
             'namespace Commandfall.Core', '{',
             '    public static partial class SliceContent', '    {',
             f'        public const string Version = "rr.slice.content-{data["version"]}";', '',
             '        public static readonly ModuleDef[] Modules =', '        {']
    for m in data['modules']:
        c = m['cost']
        stats = ', '.join(f'{s.capitalize()} = {m[s]}' for s in STATS if m.get(s, 0) != 0)
        lines.append(f'            new ModuleDef {{ Id = {cs(m["id"])}, Name = {cs(m["name"])}, Slot = {cs(m["slot"])}, Visual = {cs(m["visual"])}, {stats},')
        lines.append(f'                CostEnergy = {c["energy"]}, CostMaterials = {c["materials"]}, CostCredits = {c["credits"]}, Summary = {cs(m["summary"])} }},')
    lines += ['        };', '', '        public static readonly LoadoutDef[] Loadouts =', '        {']
    for l in data['loadouts']:
        units = ', '.join(cs(u) for u in l['units'])
        lines.append(f'            new LoadoutDef {{ Id = {cs(l["id"])}, Faction = FactionId.{l["faction"]}, Name = {cs(l["name"])}, Units = new[] {{ {units} }}, Note = {cs(l["note"])} }},')
    lines += ['        };', '    }', '}', '']
    return '\n'.join(lines)


def main():
    data = json.load(open(SRC, encoding='utf-8'))
    errors = validate(data)
    for e in errors: print('ERROR', e)
    if errors: sys.exit(1)
    print(f'ok: {len(data["modules"])} modules, {len(data["loadouts"])} loadouts')
    if '--check' in sys.argv: return
    out = generate(data)
    open(OUT, 'w', encoding='utf-8', newline='\n').write(out)
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
